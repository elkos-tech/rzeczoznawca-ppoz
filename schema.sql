-- =====================================================================
--  10. ZGŁOSZENIA BŁĘDÓW W PYTANIACH
--      Każdy zalogowany może zgłosić pytanie do weryfikacji (błędny klucz,
--      literówka, nieaktualny przepis). Zgłoszenie widzi autor i administrator.
--      source:        kgpsp (baza egzaminu), apoz (studia), user (pytania użytkowników)
--      question_ref:  identyfikator pytania w danej bazie
--      snapshot:      treść pytania i klucz z chwili zgłoszenia (dla admina)
--      status:        open → accepted (zasadne) / rejected (niezasadne)
-- =====================================================================
create table if not exists public.reports (
  id           bigint generated by default as identity primary key,
  user_id      uuid not null references public.profiles(id) on delete cascade,
  source       text not null check (source in ('kgpsp', 'apoz', 'user')),
  question_ref text not null check (char_length(question_ref) between 1 and 120),
  kind         text not null default 'answer'
               check (kind in ('answer', 'content', 'explanation', 'law', 'other')),
  suggested    text check (char_length(suggested) <= 20),
  comment      text not null check (char_length(btrim(comment)) between 5 and 2000),
  snapshot     jsonb not null default '{}'::jsonb
               check (char_length(snapshot::text) <= 8000),
  status       text not null default 'open'
               check (status in ('open', 'accepted', 'rejected')),
  admin_note   text check (char_length(admin_note) <= 1000),
  created_at   timestamptz not null default now(),
  resolved_at  timestamptz
);

create index if not exists reports_user_idx   on public.reports (user_id);
create index if not exists reports_status_idx on public.reports (status);
create index if not exists reports_ref_idx    on public.reports (source, question_ref);

-- jedna osoba = najwyżej jedno OTWARTE zgłoszenie do danego pytania
create unique index if not exists reports_one_open
  on public.reports (user_id, source, question_ref) where status = 'open';

-- daty ustawia serwer, nie przeglądarka
create or replace function public.reports_stamp()
returns trigger language plpgsql as $$
begin
  if tg_op = 'INSERT' then
    new.created_at  := now();
    new.resolved_at := null;
  elsif new.status is distinct from old.status then
    new.resolved_at := case when new.status = 'open' then null else now() end;
  end if;
  return new;
end $$;

drop trigger if exists reports_stamp on public.reports;
create trigger reports_stamp
  before insert or update on public.reports
  for each row execute function public.reports_stamp();

alter table public.reports enable row level security;

drop policy if exists reports_read       on public.reports;
drop policy if exists reports_insert_own on public.reports;
drop policy if exists reports_delete_own on public.reports;
drop policy if exists reports_admin      on public.reports;

-- widzisz własne zgłoszenia, administrator wszystkie
create policy reports_read on public.reports
  for select to authenticated
  using (user_id = auth.uid() or public.is_admin());

-- zgłosić można tylko we własnym imieniu i tylko jako „open”, bez uwagi admina
create policy reports_insert_own on public.reports
  for insert to authenticated
  with check (user_id = auth.uid() and status = 'open' and admin_note is null);

-- wycofać można własne zgłoszenie, dopóki nie zostało rozpatrzone
create policy reports_delete_own on public.reports
  for delete to authenticated
  using (user_id = auth.uid() and status = 'open');

-- rozpatrywanie (zmiana statusu, uwaga, usuwanie) tylko administrator
create policy reports_admin on public.reports
  for all to authenticated
  using (public.is_admin()) with check (public.is_admin());

grant select, insert, update, delete on public.reports to authenticated;

-- Ile otwartych zgłoszeń ma każde pytanie. Zwraca same liczby (bez autorów
-- i treści), więc każdy zalogowany widzi przy pytaniu znaczek „zgłoszone”.
create or replace function public.report_counts()
returns table (source text, question_ref text, n bigint)
language sql
stable
security definer
set search_path = public
as $$
  select r.source, r.question_ref, count(*)
  from public.reports r
  where r.status = 'open'
  group by r.source, r.question_ref;
$$;

revoke all on function public.report_counts() from public, anon;
grant execute on function public.report_counts() to authenticated;


-- =====================================================================
--  11. CZAT – jeden wspólny pokój dla zalogowanych
--      Wiadomości czyta każdy zalogowany, pisze każdy we własnym imieniu.
--      Usunąć może autor albo administrator. Edycji nie ma.
-- =====================================================================
create table if not exists public.messages (
  id         bigint generated by default as identity primary key,
  user_id    uuid not null references public.profiles(id) on delete cascade,
  body       text not null check (char_length(btrim(body)) between 1 and 1000),
  created_at timestamptz not null default now()
);

create index if not exists messages_created_idx on public.messages (created_at desc);

-- data z serwera + hamulec antyspamowy: najwyżej 12 wiadomości na minutę od osoby
create or replace function public.messages_guard()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  new.created_at := now();
  if (select count(*) from public.messages m
      where m.user_id = new.user_id
        and m.created_at > now() - interval '1 minute') >= 12 then
    raise exception 'chat_rate_limit';
  end if;
  return new;
end $$;

drop trigger if exists messages_guard on public.messages;
create trigger messages_guard
  before insert on public.messages
  for each row execute function public.messages_guard();

alter table public.messages enable row level security;

drop policy if exists messages_read       on public.messages;
drop policy if exists messages_insert_own on public.messages;
drop policy if exists messages_delete     on public.messages;

create policy messages_read on public.messages
  for select to authenticated using (true);

create policy messages_insert_own on public.messages
  for insert to authenticated with check (user_id = auth.uid());

create policy messages_delete on public.messages
  for delete to authenticated
  using (user_id = auth.uid() or public.is_admin());

grant select, insert, delete on public.messages to authenticated;

-- wiadomości „na żywo” (Supabase Realtime); blok można uruchamiać wielokrotnie
do $$
begin
  if exists (select 1 from pg_publication where pubname = 'supabase_realtime')
     and not exists (select 1 from pg_publication_tables
                     where pubname = 'supabase_realtime'
                       and schemaname = 'public' and tablename = 'messages') then
    alter publication supabase_realtime add table public.messages;
  end if;
end $$;

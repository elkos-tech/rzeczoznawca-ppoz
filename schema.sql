-- =====================================================================
--  1. PROFILE UŻYTKOWNIKÓW
--     Konta (e-mail, hasło) trzyma sam Supabase w schemacie auth.
--     Tutaj przechowujemy tylko widoczny dla innych pseudonim.
-- =====================================================================
create table if not exists public.profiles (
  id         uuid primary key references auth.users(id) on delete cascade,
  nick       text not null unique check (char_length(btrim(nick)) between 2 and 32),
  created_at timestamptz not null default now()
);


-- =====================================================================
--  2. ADMINISTRATORZY (moderacja pytań publicznych)
--     Tabela celowo BEZ reguł zapisu – wpis może dodać wyłącznie
--     właściciel projektu z SQL Editora. Nikt nie nada sobie praw z aplikacji.
-- =====================================================================
create table if not exists public.admins (
  user_id uuid primary key references auth.users(id) on delete cascade,
  added_at timestamptz not null default now()
);

create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (select 1 from public.admins a where a.user_id = auth.uid());
$$;


-- =====================================================================
--  3. POSTĘP NAUKI (synchronizacja między urządzeniami)
--     Cały stan z localStorage trzymany jako JSON – jeden wiersz na osobę.
-- =====================================================================
create table if not exists public.progress (
  user_id    uuid primary key references auth.users(id) on delete cascade,
  data       jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now()
);


-- =====================================================================
--  4. PYTANIA UŻYTKOWNIKÓW
--     status:
--       private   – widoczne tylko dla autora
--       pending   – autor zgłosił do publikacji, czeka na moderację
--       approved  – zatwierdzone przez admina, widoczne dla wszystkich
--       rejected  – odrzucone, wraca do autora z uwagą (review_note)
-- =====================================================================
create table if not exists public.questions (
  id          bigint generated by default as identity primary key,
  author_id   uuid not null references public.profiles(id) on delete cascade,
  question    text not null check (char_length(btrim(question)) between 10 and 2000),
  opt_a       text not null check (char_length(btrim(opt_a)) between 1 and 600),
  opt_b       text not null check (char_length(btrim(opt_b)) between 1 and 600),
  opt_c       text not null check (char_length(btrim(opt_c)) between 1 and 600),
  answer      text not null check (answer in ('a','b','c')),
  explanation text check (char_length(explanation) <= 5000),
  legal       text[] not null default '{}'::text[]
              check (coalesce(array_length(legal, 1), 0) <= 10),
  category    text not null default 'Pytania użytkowników'
              check (char_length(btrim(category)) between 2 and 80),
  status      text not null default 'private'
              check (status in ('private', 'pending', 'approved', 'rejected')),
  review_note text check (char_length(review_note) <= 500),
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);

create index if not exists questions_author_idx on public.questions (author_id);
create index if not exists questions_status_idx on public.questions (status);


-- =====================================================================
--  5. AUTOMATYZACJE
-- =====================================================================

-- 5a. updated_at odświeżane przy każdej zmianie pytania
create or replace function public.touch_updated_at()
returns trigger language plpgsql as $$
begin
  new.updated_at = now();
  return new;
end $$;

drop trigger if exists questions_touch on public.questions;
create trigger questions_touch
  before update on public.questions
  for each row execute function public.touch_updated_at();


-- 5b. profil zakładany automatycznie przy rejestracji (także przez Google).
--     Pseudonim: z formularza rejestracji, inaczej z nazwy Google,
--     inaczej z części e-maila przed @. Przy kolizji dopisuje _1, _2, ...
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  base_nick text;
  try_nick  text;
  n         int := 0;
begin
  base_nick := nullif(btrim(coalesce(
                 new.raw_user_meta_data ->> 'nick',
                 new.raw_user_meta_data ->> 'full_name',
                 new.raw_user_meta_data ->> 'name',
                 split_part(coalesce(new.email, ''), '@', 1)
               )), '');
  base_nick := left(coalesce(base_nick, 'uzytkownik'), 28);
  if char_length(base_nick) < 2 then
    base_nick := base_nick || '_u';
  end if;

  try_nick := base_nick;
  while exists (select 1 from public.profiles p where lower(p.nick) = lower(try_nick)) loop
    n := n + 1;
    try_nick := left(base_nick, 24) || '_' || n::text;
    exit when n > 9999;
  end loop;

  insert into public.profiles (id, nick)
  values (new.id, try_nick)
  on conflict (id) do nothing;

  return new;
exception when others then
  -- rejestracja nie może się wywalić z powodu profilu; profil domknie aplikacja
  return new;
end $$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();


-- =====================================================================
--  6. BEZPIECZEŃSTWO (Row Level Security)
--     Bez tego każdy z kluczem publicznym widziałby wszystko.
--     Reguły działają w bazie – pytanie prywatne fizycznie nie opuści serwera.
-- =====================================================================
alter table public.profiles  enable row level security;
alter table public.admins    enable row level security;
alter table public.progress  enable row level security;
alter table public.questions enable row level security;

-- --- profile: pseudonimy widoczne dla zalogowanych (podpis pod pytaniem) ---
drop policy if exists profiles_read        on public.profiles;
drop policy if exists profiles_insert_own  on public.profiles;
drop policy if exists profiles_update_own  on public.profiles;

create policy profiles_read on public.profiles
  for select to authenticated using (true);
create policy profiles_insert_own on public.profiles
  for insert to authenticated with check (id = auth.uid());
create policy profiles_update_own on public.profiles
  for update to authenticated using (id = auth.uid()) with check (id = auth.uid());

-- --- admini: każdy widzi tylko czy sam jest adminem; zapisu brak ---
drop policy if exists admins_read_own on public.admins;
create policy admins_read_own on public.admins
  for select to authenticated using (user_id = auth.uid());

-- --- postęp nauki: wyłącznie własny ---
drop policy if exists progress_own on public.progress;
create policy progress_own on public.progress
  for all to authenticated using (user_id = auth.uid()) with check (user_id = auth.uid());

-- --- pytania ---
drop policy if exists questions_read       on public.questions;
drop policy if exists questions_insert_own on public.questions;
drop policy if exists questions_update_own on public.questions;
drop policy if exists questions_delete_own on public.questions;
drop policy if exists questions_admin      on public.questions;

-- widzisz: swoje + zatwierdzone + (jeśli admin) wszystkie
create policy questions_read on public.questions
  for select to authenticated
  using (author_id = auth.uid() or status = 'approved' or public.is_admin());

-- dodać można tylko własne i tylko jako prywatne albo zgłoszone do moderacji
create policy questions_insert_own on public.questions
  for insert to authenticated
  with check (author_id = auth.uid() and status in ('private', 'pending'));

-- edycja własnego pytania zawsze zrzuca je z powrotem do private/pending,
-- więc po zmianie treści zatwierdzone pytanie musi przejść moderację ponownie
create policy questions_update_own on public.questions
  for update to authenticated
  using (author_id = auth.uid())
  with check (author_id = auth.uid() and status in ('private', 'pending'));

create policy questions_delete_own on public.questions
  for delete to authenticated
  using (author_id = auth.uid());

-- admin: pełne prawa (zatwierdzanie, odrzucanie, usuwanie)
create policy questions_admin on public.questions
  for all to authenticated
  using (public.is_admin()) with check (public.is_admin());


-- =====================================================================
--  7. UPRAWNIENIA ROLI "authenticated"
--     (Supabase zwykle nadaje je sam – podane jawnie dla pewności.)
-- =====================================================================
grant usage on schema public to authenticated;
grant select, insert, update          on public.profiles  to authenticated;
grant select, insert, update, delete  on public.progress  to authenticated;
grant select, insert, update, delete  on public.questions to authenticated;
grant select                          on public.admins    to authenticated;
grant execute on function public.is_admin() to authenticated;


